// 从 thirdparty/inkEngine/ink-engine.js 生成 src/core/ink-shaders.ts。
// 只做固定的文本替换：GLSL 1.0 → 3.00、gl_FragCoord/纹理坐标翻到 inkEngine 的左下原点、去掉遮罩分支、
// 编码通道补上 p5 拷贝时的 alpha 行为。授权与归属见 THIRD_PARTY_NOTICES.md。
// 用法：node scripts/port-inkengine-shaders.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'thirdparty/inkEngine/ink-engine.js'), 'utf8');
const start = source.indexOf('const SHADER_SOURCES = {');
const end = source.indexOf('};', start);
// eslint-disable-next-line no-new-func
const shaders = new Function(`return (${source.slice(start + 'const SHADER_SOURCES = '.length, end + 1)});`)();

function pretty(glsl) {
  return glsl
    .replace(/;\s*/g, ';\n')
    .replace(/\{\s*/g, '{\n')
    .replace(/\}\s*/g, '}\n')
    .replace(/\n+/g, '\n')
    .replace(/for \(([^;]*);\n([^;]*);\n/g, 'for ($1; $2; ')
    .trim();
}

const HELPERS = [
  'in vec2 vPixel;',
  'out vec4 finalColor;',
  'uniform vec2 uCanvas;',
  // inkEngine samples with gl_FragCoord-derived coordinates (origin bottom-left); Pixi textures are top-down.
  'vec4 T(sampler2D s, vec2 c) { return texture(s, vec2(c.x, 1.0 - c.y)); }',
  'vec2 inkFragCoord() { return vec2(vPixel.x, uCanvas.y - vPixel.y); }',
].join('\n');

function convert(name, extra = (s) => s) {
  let s = shaders[`./shaders/${name}`];
  if (!s) throw new Error(`missing shader ${name}`);
  s = s.replace(/#ifdef GL_ES\s*precision \w+ float;\s*#endif/, '');
  s = s.replace(/precision \w+ float;/, '');
  s = s.replace(/#define PROCESSING_COLOR_SHADER/, '');
  s = s.replace(/uniform vec4 rect;/, '');
  s = s.replace(/uniform vec2 invResolution;/, '');
  s = s.replace(/uniform float useMask;/, '');
  s = s.replace(/uniform sampler2D maskTex;/, '');
  s = s.replace(/if \(useMask > 0\.5\)\{[^{}]*\{[^{}]*\}\s*\}/g, '');
  s = s.replace(/\(gl_FragCoord\.xy - rect\.xy\)\/ rect\.zw/g, '(inkFragCoord() / uCanvas)');
  s = s.replace(/1\.0 \/ rect\.zw/g, '(1.0 / uCanvas)');
  s = s.replace(/rect\.zw/g, 'uCanvas');
  s = s.replace(/rect\.xy/g, 'vec2(0.0)');
  s = s.replace(/rect\.z\b/g, 'uCanvas.x');
  s = s.replace(/invResolution/g, '(1.0 / uCanvas)');
  s = s.replace(/gl_FragCoord\.xy/g, 'inkFragCoord()');
  s = s.replace(/texture2D\(/g, 'T(');
  s = s.replace(/gl_FragColor/g, 'finalColor');
  // Pixi prefixes the shader with `#define in varying` under GL_ES, which turns an `in` parameter
  // into an illegal `varying` parameter. `in` is the default qualifier, so drop it. Leave `inout` alone.
  s = s.replace(/(\(|,)\s*in\s+(?=vec|float|int|mat|sampler)/g, '$1 ');
  s = extra(s);
  if (/useMask|maskTex|rect\.|gl_Frag|texture2D/.test(s)) throw new Error(`unconverted tokens left in ${name}`);
  return `${HELPERS}\n${pretty(s)}`;
}

const out = {
  feedback: convert('feedback.frag'),
  encode: convert('encode.frag', (s) => {
    // p5 copies the encoded buffer onto a white, opaque finalBuffer with blend(ONE, ONE_MINUS_SRC_ALPHA):
    // the stored 8-bit alpha becomes 1 and (1 - alpha) is added to the colour. Do that here.
    const tail = 'finalColor = vec4(_x75,_x103);';
    if (!s.includes(tail)) throw new Error('encode tail not found');
    return s.replace(tail, 'float inkA = floor(_x103 * 255.0 + 0.5) / 255.0;\nfinalColor = vec4(clamp(_x75 + (1.0 - inkA), 0.0, 1.0), 1.0);');
  }),
  typeMap: convert('typeMapEncode.frag'),
  composite: convert('composite.frag'),
  realtime: convert('realtime.frag'),
  forceMap: convert('mapFrag.frag'),
  distort: convert('distort.frag'),
  flow: convert('flow.frag'),
  metallic: convert('metallic.frag'),
};

const header = `/**
 * GLSL 3.00 ports of thirdparty/inkEngine shaders (feedback, encode, typeMapEncode,
 * composite, realtime, mapFrag, distort, flow, metallic), generated by scripts/port-inkengine-shaders.mjs.
 * Changes are mechanical: texture2D/gl_FragCoord go through T()/inkFragCoord() so coordinates keep
 * inkEngine's bottom-left origin, the mask branches are dropped, and encode writes the colour p5's
 * opaque copy would store. Ported with attribution under the owner-stated inkField authorization
 * (THIRD_PARTY_NOTICES.md). Do not edit by hand; rerun the script.
 */
`;
const body = Object.entries(out)
  .map(([key, glsl]) => `export const INK_${key.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase()}_FRAGMENT = ${JSON.stringify(glsl)};`)
  .join('\n\n');
writeFileSync(join(root, 'src/core/ink-shaders.ts'), `${header}\n${body}\n`);
console.log('wrote src/core/ink-shaders.ts', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
